def generate_story(prompt, outfile):
    print(f"Generating story for {outfile} via Ollama shosetsu:latest...")
    req = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps({
            "model": "shosetsu:latest",
            "prompt": prompt,
            "stream": False
        }).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(req, timeout=300) as res:
        data = json.loads(res.read().decode("utf-8"))
        novel_text = data.get("response", "")
    with open(outfile, "w", encoding="utf-8") as f:
        f.write(novel_text)
    print(f"Saved {outfile} ({len(novel_text)} chars)")

if __name__ == "__main__":
    generate_story(p14_prompt, "content/ep14_novel_raw.txt")
