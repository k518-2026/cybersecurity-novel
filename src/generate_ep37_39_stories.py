def generate_story(ep_num, prompt):
    print(f"Generating Episode {ep_num} story via Ollama shosetsu:latest...")
    payload = {
        "model": "shosetsu:latest",
        "prompt": prompt,
        "stream": False,
        "options": {
            "num_predict": 4096,
            "temperature": 0.75,
            "top_p": 0.9
        }
    }
    req = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=600) as res:
            data = json.loads(res.read().decode("utf-8"))
            response_text = data.get("response", "").strip()
            out_file = os.path.join(CONTENT_DIR, f"ep{ep_num}_novel_raw.txt")
            with open(out_file, "w", encoding="utf-8") as f:
                f.write(response_text)
            print(f"[Saved] {out_file} in {time.time()-t0:.2f}s ({len(response_text)} chars)")
            return True
    except Exception as e:
        print(f"[Error] Episode {ep_num} failed: {e}")
        return False

